create table empresas (
  id bigint generated by default as identity primary key,
  nome varchar(160) not null,
  slug varchar(160) not null unique,
  ativo boolean not null default true,
  criado_em timestamp with time zone not null
);

create table usuarios (
  id bigint generated by default as identity primary key,
  empresa_id bigint not null references empresas(id),
  nome varchar(120) not null,
  email varchar(180) not null unique,
  senha_hash varchar(100) not null,
  perfil varchar(20) not null,
  ativo boolean not null default true,
  criado_em timestamp with time zone not null
);

create table produtos (
  id bigint generated by default as identity primary key,
  empresa_id bigint not null references empresas(id),
  gtin varchar(14) not null,
  nome varchar(240) not null,
  laboratorio varchar(160),
  apresentacao varchar(160),
  categoria varchar(120),
  ativo boolean not null default true,
  criado_em timestamp with time zone not null,
  atualizado_em timestamp with time zone not null,
  constraint uk_produto_empresa_gtin unique(empresa_id, gtin)
);

create table cotacoes (
  id bigint generated by default as identity primary key,
  empresa_id bigint not null references empresas(id),
  nome varchar(180) not null,
  token_publico varchar(80) unique,
  status varchar(20) not null,
  expira_em timestamp with time zone,
  criado_por bigint not null references usuarios(id),
  criado_em timestamp with time zone not null,
  atualizado_em timestamp with time zone not null
);

create table itens_cotacao (
  id bigint generated by default as identity primary key,
  cotacao_id bigint not null references cotacoes(id) on delete cascade,
  produto_id bigint not null references produtos(id),
  quantidade_solicitada integer not null check(quantidade_solicitada > 0),
  constraint uk_cotacao_produto unique(cotacao_id, produto_id)
);

create table respostas_cotacao (
  id bigint generated by default as identity primary key,
  cotacao_id bigint not null references cotacoes(id) on delete cascade,
  token_resposta varchar(80) not null unique,
  nome_representante varchar(120) not null,
  nome_distribuidora varchar(160) not null,
  telefone varchar(30) not null,
  email varchar(180),
  documento_distribuidora varchar(20),
  status varchar(20) not null,
  enviado_em timestamp with time zone,
  criado_em timestamp with time zone not null
);

create table itens_resposta_cotacao (
  id bigint generated by default as identity primary key,
  resposta_cotacao_id bigint not null references respostas_cotacao(id) on delete cascade,
  item_cotacao_id bigint not null references itens_cotacao(id),
  preco_unitario numeric(15,4),
  quantidade_disponivel integer,
  disponivel boolean not null default false,
  observacao varchar(500),
  constraint uk_resposta_item_cotacao unique(resposta_cotacao_id, item_cotacao_id)
);

create index idx_produtos_empresa on produtos(empresa_id);
create index idx_cotacoes_empresa on cotacoes(empresa_id);
create index idx_respostas_cotacao on respostas_cotacao(cotacao_id);
